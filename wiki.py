#!/usr/bin/env python3
"""Bookkeeping for an LLM-maintained second brain (Python 3.8+ stdlib only).

The assistant writes the pages; this tool does the parts that must not depend
on memory: page skeletons, the index, the log, search and a health check.
"""
import argparse
import datetime
import os
import re
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
WIKI = os.path.join(ROOT, "wiki")
RAW = os.path.join(ROOT, "raw")
TEMPLATES = os.path.join(ROOT, "templates")
INDEX = os.path.join(WIKI, "index.md")
LOG = os.path.join(WIKI, "log.md")
GRAPH = os.path.join(WIKI, "graph.md")

# page type -> folder under wiki/
TYPES = {
    "source": "sources",
    "concept": "concepts",
    "entity": "entities",
    "idea": "ideas",
    "question": "questions",
}
TYPE_ORDER = ["overview", "idea", "concept", "entity", "question", "source"]
GENERATED = {"index", "log", "graph"}  # bookkeeping pages, not knowledge
SPECIAL = GENERATED | {"overview"}
REQUIRED = ["title", "type", "summary", "created", "updated", "status"]
STATUSES = {"seed", "growing", "stable", "archived"}
STALE_DAYS = 120
LINK_RE = re.compile(r"\[\[([^\]|#]+)(?:#[^\]|]*)?(?:\|[^\]]*)?\]\]")
SECRET_RES = [
    re.compile(r"sk-[A-Za-z0-9_-]{20,}"),
    re.compile(r"gh[pousr]_[A-Za-z0-9]{30,}"),
    re.compile(r"AKIA[0-9A-Z]{16}"),
    re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----"),
    re.compile(r"(?i)\b(password|passwd|api[_-]?key|secret)\s*[:=]\s*\S{6,}"),
]
MERMAID_MAX = 80  # larger maps stop being readable on GitHub
COLORS = {"idea": "#f6c85f", "concept": "#6fa8dc", "entity": "#93c47d",
          "question": "#c27ba0", "source": "#cccccc"}


def today():
    return datetime.date.today().isoformat()


def rel(path):
    return os.path.relpath(path, ROOT).replace(os.sep, "/")


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def slugify(title):
    slug = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")
    return slug[:60].rstrip("-") or "untitled"


def parse_frontmatter(text):
    """Parse the simple `key: value` / `key: [a, b]` frontmatter used here."""
    if not text.startswith("---"):
        return None, text
    end = text.find("\n---", 3)
    if end == -1:
        return None, text
    meta = {}
    for line in text[3:end].strip().splitlines():
        if ":" not in line or line.lstrip().startswith("#"):
            continue
        key, value = line.split(":", 1)
        value = value.strip()
        if value.startswith("[") and value.endswith("]"):
            value = [v.strip().strip("'\"") for v in value[1:-1].split(",") if v.strip()]
        else:
            value = value.strip("'\"")
        meta[key.strip()] = value
    body = text[end + 4:].lstrip("\n")
    return meta, body


def pages():
    """Yield (name, path) for every markdown page under wiki/."""
    for dirpath, _, files in os.walk(WIKI):
        for fn in sorted(files):
            if fn.endswith(".md"):
                yield fn[:-3], os.path.join(dirpath, fn)


def raw_files():
    for dirpath, dirs, files in os.walk(RAW):
        dirs[:] = [d for d in dirs if d != "assets"]
        for fn in sorted(files):
            if fn not in ("README.md", ".gitkeep") and not fn.startswith("."):
                yield rel(os.path.join(dirpath, fn))


def as_list(value):
    if not value:
        return []
    return value if isinstance(value, list) else [value]


# ---------------------------------------------------------------- commands

def cmd_new(args):
    folder = TYPES[args.type]
    slug = args.slug or slugify(args.title)
    existing = {name: path for name, path in pages()}
    if slug in existing:
        sys.exit("EXISTS: [[%s]] is already %s; update it instead" % (slug, rel(existing[slug])))
    if args.raw:
        raw_path = args.raw.replace("\\", "/")
        if not os.path.isfile(os.path.join(ROOT, raw_path)):
            sys.exit("NOT FOUND: %s" % raw_path)
    template = read(os.path.join(TEMPLATES, args.type + ".md"))
    text = (template.replace("{{title}}", args.title)
            .replace("{{slug}}", slug)
            .replace("{{date}}", today())
            .replace("{{sources}}", args.raw.replace("\\", "/") if args.raw else ""))
    path = os.path.join(WIKI, folder, slug + ".md")
    write(path, text)
    print("CREATED %s  (link it as [[%s]])" % (rel(path), slug))


def cmd_index(args):
    groups = {}
    for name, path in pages():
        if name in GENERATED:
            continue
        meta, _ = parse_frontmatter(read(path))
        meta = meta or {}
        kind = meta.get("type") or "unknown"
        groups.setdefault(kind, []).append((name, meta))
    lines = [
        "# Index",
        "",
        "Generated by `wiki.py index` on %s. Do not edit by hand." % today(),
        "Read this first, then open the pages a question needs.",
        "[[graph]] shows how the pages and ideas connect.",
        "",
    ]
    order = TYPE_ORDER + sorted(k for k in groups if k not in TYPE_ORDER)
    total = 0
    for kind in order:
        entries = groups.get(kind)
        if not entries:
            continue
        heading = TYPES.get(kind, kind).capitalize() if kind != "overview" else "Overview"
        lines += ["## %s (%d)" % (heading, len(entries)), ""]
        for name, meta in sorted(entries, key=lambda e: e[0]):
            extra = []
            if meta.get("status") and meta.get("status") != "stable":
                extra.append(meta["status"])
            if meta.get("updated"):
                extra.append(meta["updated"])
            tail = " (%s)" % ", ".join(extra) if extra else ""
            lines.append("- [[%s]]: %s%s" % (name, meta.get("summary") or "(no summary)", tail))
            total += 1
        lines.append("")
    write(INDEX, "\n".join(lines))
    print("INDEX %d page(s) -> %s" % (total, rel(INDEX)))


def cmd_log(args):
    if not os.path.exists(LOG):
        write(LOG, "# Log\n\nAppend-only. Written by `wiki.py log`.\n")
    entry = "\n## [%s] %s | %s\n" % (today(), args.op, args.title)
    if args.pages:
        entry += "\n- pages: %s\n" % ", ".join("[[%s]]" % p for p in args.pages)
    if args.note:
        entry += "- note: %s\n" % args.note
    with open(LOG, "a", encoding="utf-8", newline="\n") as f:
        f.write(entry)
    print("LOGGED %s | %s" % (args.op, args.title))


def last_log_entries(n):
    if not os.path.exists(LOG):
        return []
    return [l for l in read(LOG).splitlines() if l.startswith("## [")][-n:]


def ingested_raw():
    used = set()
    for _, path in pages():
        meta, _ = parse_frontmatter(read(path))
        for s in as_list((meta or {}).get("sources")):
            used.add(s.replace("\\", "/"))
    return used


def cmd_status(args):
    counts = {}
    for name, path in pages():
        if name in GENERATED:
            continue
        meta, _ = parse_frontmatter(read(path))
        kind = (meta or {}).get("type") or "unknown"
        counts[kind] = counts.get(kind, 0) + 1
    print("pages: " + (", ".join("%s %d" % (k, v) for k, v in sorted(counts.items())) or "none"))
    used = ingested_raw()
    pending = [r for r in raw_files() if r not in used]
    print("raw sources not yet ingested: %d" % len(pending))
    for r in pending[:10]:
        print("  - " + r)
    inbox = os.path.join(ROOT, "inbox.md")
    if os.path.exists(inbox):
        items = [l for l in read(inbox).splitlines() if l.startswith("- ")]
        print("inbox items: %d" % len(items))
    print("last log entries:")
    for l in last_log_entries(5) or ["  (none)"]:
        print("  " + l)


def cmd_search(args):
    terms = [t.lower() for t in args.terms]
    results = []
    for name, path in pages():
        if name in GENERATED:
            continue
        text = read(path)
        low = text.lower()
        score = sum(low.count(t) for t in terms)
        if not score or not all(t in low for t in terms):
            continue
        meta, _ = parse_frontmatter(text)
        title = ((meta or {}).get("title") or "").lower()
        score += 5 * sum(t in title or t in name for t in terms)
        results.append((score, name, (meta or {}).get("summary", "")))
    for score, name, summary in sorted(results, reverse=True)[: args.limit]:
        print("[[%s]] (%d) %s" % (name, score, summary))
    if not results:
        print("no matches")


def cmd_lint(args):
    problems = []
    all_pages = dict(pages())
    inbound = {name: 0 for name in all_pages}
    raw_set = set(raw_files())
    used = set()
    cutoff = datetime.date.today() - datetime.timedelta(days=STALE_DAYS)
    for name, path in sorted(all_pages.items()):
        text = read(path)
        where = rel(path)
        for rx in SECRET_RES:
            if rx.search(text):
                problems.append("SECRET?  %s looks like it contains a credential; remove it" % where)
                break
        if name in GENERATED:
            continue
        meta, body = parse_frontmatter(text)
        if meta is None:
            problems.append("FRONTMATTER  %s has none" % where)
            meta = {}
        for key in REQUIRED:
            if not meta.get(key):
                problems.append("FRONTMATTER  %s missing '%s'" % (where, key))
        if meta.get("status") and meta["status"] not in STATUSES:
            problems.append("FRONTMATTER  %s status '%s' not one of %s" % (where, meta["status"], "/".join(sorted(STATUSES))))
        expected = TYPES.get(meta.get("type", ""))
        if expected and os.path.basename(os.path.dirname(path)) != expected:
            problems.append("PLACEMENT  %s is type '%s' but not in wiki/%s/" % (where, meta["type"], expected))
        for s in as_list(meta.get("sources")):
            s = s.replace("\\", "/")
            used.add(s)
            if s.startswith("raw/") and s not in raw_set:
                problems.append("SOURCE  %s cites %s, which does not exist" % (where, s))
        if meta.get("type") == "source" and not as_list(meta.get("sources")):
            problems.append("SOURCE  %s is a source summary with no 'sources'" % where)
        if str(meta.get("summary", "")).startswith("TODO"):
            problems.append("TEMPLATE  %s summary is still the template's TODO" % where)
        if "{{" in body:
            problems.append("TEMPLATE  %s still has unfilled {{placeholders}}" % where)
        try:
            updated = datetime.date.fromisoformat(meta.get("updated", ""))
            if updated < cutoff and meta.get("status") != "archived":
                problems.append("STALE  %s not updated since %s; review or archive" % (where, updated))
        except ValueError:
            if meta.get("updated"):
                problems.append("FRONTMATTER  %s 'updated' is not YYYY-MM-DD" % where)
        for target in LINK_RE.findall(body):
            target = target.strip()
            if target in all_pages:
                if target != name:
                    inbound[target] += 1
            elif not os.path.exists(os.path.join(ROOT, target)):
                problems.append("LINK  %s -> [[%s]] has no page" % (where, target))
    for name, n in sorted(inbound.items()):
        if n == 0 and name not in SPECIAL:
            problems.append("ORPHAN  [[%s]] has no links pointing to it" % name)
    for r in sorted(raw_set - used):
        problems.append("UNINGESTED  %s has no source page" % r)
    for p in problems:
        print(p)
    print("%d problem(s)" % len(problems))
    return 1 if problems else 0


# ------------------------------------------------------------------ graph

def build_graph():
    """Return (nodes, links, neighbours) for the knowledge pages.

    links[a][b] is the section heading under which page a links to page b.
    The overview is left out: it links to everything and hides the structure.
    """
    nodes = {}
    for name, path in pages():
        if name in SPECIAL:
            continue
        meta, body = parse_frontmatter(read(path))
        nodes[name] = {"meta": meta or {}, "body": body}
    links = {}
    for name, node in nodes.items():
        out, section = {}, ""
        for line in node["body"].splitlines():
            if line.startswith("#"):
                section = line.lstrip("#").strip()
                continue
            for target in LINK_RE.findall(line):
                target = target.strip()
                if target in nodes and target != name:
                    out.setdefault(target, section)
        links[name] = out
    nb = {name: set() for name in nodes}
    for a, out in links.items():
        for b in out:
            nb[a].add(b)
            nb[b].add(a)
    return nodes, links, nb


def kind_of(nodes, name):
    return nodes[name]["meta"].get("type") or "unknown"


def title_of(nodes, name):
    return nodes[name]["meta"].get("title") or name


def sections(body):
    out, current = {}, None
    for line in body.splitlines():
        if line.startswith("## "):
            current = line[3:].strip()
            out[current] = []
        elif current is not None:
            out[current].append(line)
    return {k: "\n".join(v).strip() for k, v in out.items()}


def idea_profile(nodes, name):
    meta, body = nodes[name]["meta"], nodes[name]["body"]
    sec = sections(body)
    evidence = sec.get("Evidence (sourced)", "")
    test = sec.get("Cheapest falsification test", "")
    history = [l[2:].strip() for l in sec.get("Verdict history", "").splitlines() if l.startswith("- ")]
    return {
        "stage": meta.get("stage", "?"),
        "verdict": meta.get("verdict", "?"),
        "confidence": meta.get("confidence", "?"),
        "sources": len(as_list(meta.get("sources"))),
        "evidence": sum(1 for t in LINK_RE.findall(evidence) if t.strip() in nodes) + evidence.count("http"),
        # template placeholders contain "<...>"; count only filled-in lines
        "hypotheses": sum(l.count("[hypothesis]") for l in body.splitlines() if "<" not in l),
        "test": bool(test) and not test.startswith("<"),
        "latest": history[-1] if history else "",
    }


def components(nodes, nb):
    seen, comps = set(), []
    for start in sorted(nodes, key=lambda n: (-len(nb[n]), n)):
        if start in seen:
            continue
        seen.add(start)
        stack, comp = [start], []
        while stack:
            x = stack.pop()
            comp.append(x)
            for y in nb[x] - seen:
                seen.add(y)
                stack.append(y)
        comps.append(sorted(comp, key=lambda n: (-len(nb[n]), n)))
    return sorted(comps, key=len, reverse=True)


def suggestions(nodes, nb, only=None, min_shared=2):
    """Unlinked page pairs that share neighbours, most shared first."""
    out = []
    names = sorted(nodes)
    for i, a in enumerate(names):
        for b in names[i + 1:]:
            if only and only not in (a, b):
                continue
            if b in nb[a] or kind_of(nodes, a) == kind_of(nodes, b) == "source":
                continue
            shared = nb[a] & nb[b]
            if len(shared) >= min_shared:
                out.append((len(shared), a, b, sorted(shared)))
    return sorted(out, key=lambda s: (-s[0], s[1], s[2]))


def unlinked_mentions(nodes, links):
    """(page, target) where page names target's title in its text without linking it."""
    plain = {n: LINK_RE.sub(" ", d["body"]).lower() for n, d in nodes.items()}
    found = []
    for target in sorted(nodes):
        title = title_of(nodes, target).lower()
        if len(title) < 4:
            continue
        rx = re.compile(r"(?<![a-z0-9])" + re.escape(title) + r"(?![a-z0-9])")
        for src in sorted(nodes):
            if src != target and target not in links[src] and rx.search(plain[src]):
                found.append((src, target))
    return found


def mermaid(nodes, links, shown):
    def nid(n):
        return "n_" + re.sub(r"[^A-Za-z0-9]", "_", n)
    out = ["```mermaid", "graph LR"]
    for kind, color in COLORS.items():
        out.append("  classDef %s fill:%s,stroke:#555,color:#000" % (kind, color))
    for n in sorted(shown):
        kind = kind_of(nodes, n)
        label = title_of(nodes, n).replace('"', "#quot;")
        out.append('  %s["%s"]%s' % (nid(n), label, ":::" + kind if kind in COLORS else ""))
    for a in sorted(shown):
        for b in sorted(links[a]):
            if b in shown:
                both_ideas = kind_of(nodes, a) == kind_of(nodes, b) == "idea"
                out.append("  %s %s %s" % (nid(a), "==>" if both_ideas else "-->", nid(b)))
    out.append("```")
    return out


def cmd_graph(args):
    nodes, links, nb = build_graph()
    ideas = sorted(n for n in nodes if kind_of(nodes, n) == "idea")
    n_links = sum(len(o) for o in links.values())
    L = [
        "# Graph",
        "",
        "Generated by `wiki.py graph` on %s. Do not edit by hand." % today(),
        "How the pages connect; `wiki/overview.md` is left out because it links to",
        "everything. In Obsidian, Graph view shows the same links interactively.",
        "",
        "%d page(s), %d link(s), %d idea(s)." % (len(nodes), n_links, len(ideas)),
        "",
        "## Map",
        "",
    ]
    shown = set(nodes)
    if len(shown) > MERMAID_MAX:
        shown = set(ideas).union(*(nb[i] for i in ideas)) if ideas else set()
        rank = sorted(shown or nodes, key=lambda n: (kind_of(nodes, n) != "idea", -len(nb[n]), n))
        shown = set(rank[:MERMAID_MAX])
        L += ["Showing %d of %d pages: ideas first, then the most connected." % (len(shown), len(nodes)), ""]
    if shown:
        L += ["Colours: ideas yellow, concepts blue, entities green, questions purple,",
              "sources grey. Thick arrows join two ideas.", ""]
        L += mermaid(nodes, links, shown)
    else:
        L.append("(no pages yet)")
    L.append("")

    L += ["## Ideas (%d)" % len(ideas), ""]
    if ideas:
        L += ["| Idea | Stage | Verdict | Confidence | Sources | Evidence links | Hypotheses | Falsification test | Latest verdict |",
              "|---|---|---|---|---|---|---|---|---|"]
        weak = []
        for i in ideas:
            p = idea_profile(nodes, i)
            L.append("| [[%s]] | %s | %s | %s | %d | %d | %d | %s | %s |" % (
                i, p["stage"], p["verdict"], p["confidence"], p["sources"], p["evidence"],
                p["hypotheses"], "yes" if p["test"] else "missing", p["latest"].replace("|", "/")))
            gaps = []
            if not p["evidence"]:
                gaps.append("no sourced evidence")
            if not p["test"]:
                gaps.append("no falsification test")
            if not nb[i]:
                gaps.append("not linked to any page")
            if gaps:
                weak.append("- [[%s]]: %s" % (i, ", ".join(gaps)))
        L.append("")
        if weak:
            L += ["Needs work:", ""] + weak + [""]
    else:
        L += ["(none yet)", ""]

    L += ["## How ideas relate", ""]
    pairs = []
    for x, a in enumerate(ideas):
        for b in ideas[x + 1:]:
            parts = []
            for s, t in ((a, b), (b, a)):
                if t in links[s]:
                    parts.append("[[%s]] links to [[%s]] under \"%s\"" % (s, t, links[s][t] or "top"))
            shared = sorted(nb[a] & nb[b])
            if shared:
                parts.append("share " + ", ".join("[[%s]]" % s for s in shared))
            if parts:
                pairs.append((len(shared), "- [[%s]] and [[%s]]: %s" % (a, b, "; ".join(parts))))
    L += [p for _, p in sorted(pairs, key=lambda p: -p[0])] or ["(no two ideas connect yet)"]
    L.append("")

    L += ["## Hubs (most connected)", ""]
    hubs = sorted((n for n in nodes if nb[n]), key=lambda n: (-len(nb[n]), n))[:10]
    L += ["- [[%s]] (%s): %d link(s)" % (n, kind_of(nodes, n), len(nb[n])) for n in hubs] or ["(none yet)"]
    L.append("")

    L += ["## Clusters", ""]
    comps = components(nodes, nb)
    groups = [c for c in comps if len(c) > 1]
    for k, c in enumerate(groups, 1):
        more = " and %d more" % (len(c) - 12) if len(c) > 12 else ""
        L.append("- cluster %d (%d pages): %s%s" % (k, len(c), ", ".join("[[%s]]" % n for n in c[:12]), more))
    alone = sorted(c[0] for c in comps if len(c) == 1)
    if alone:
        L.append("- unconnected: " + ", ".join("[[%s]]" % n for n in alone))
    if not comps:
        L.append("(none yet)")
    L.append("")

    L += ["## Suggested links", "", "Pages not linked to each other that share two or more neighbours.", ""]
    L += ["- [[%s]] and [[%s]] share %s" % (a, b, ", ".join("[[%s]]" % s for s in sh))
          for _, a, b, sh in suggestions(nodes, nb)[:15]] or ["(none)"]
    L.append("")

    L += ["## Unlinked mentions", "", "A page names another page's title without linking it.", ""]
    L += ["- [[%s]] mentions \"%s\" without linking [[%s]]" % (s, title_of(nodes, t), t)
          for s, t in unlinked_mentions(nodes, links)[:20]] or ["(none)"]
    L.append("")

    write(GRAPH, "\n".join(L))
    print("GRAPH %d page(s), %d link(s), %d idea(s), %d cluster(s) -> %s"
          % (len(nodes), n_links, len(ideas), len(groups), rel(GRAPH)))


def cmd_related(args):
    nodes, links, nb = build_graph()
    name = args.page
    if name not in nodes:
        sys.exit("NOT FOUND: [[%s]] (overview, index, log and graph are not in the graph)" % name)
    print("[[%s]] (%s): %s" % (name, kind_of(nodes, name), nodes[name]["meta"].get("summary", "")))
    if kind_of(nodes, name) == "idea":
        p = idea_profile(nodes, name)
        print("  stage %s | verdict %s | confidence %s | sources %d | evidence links %d | hypotheses %d | test %s"
              % (p["stage"], p["verdict"], p["confidence"], p["sources"], p["evidence"],
                 p["hypotheses"], "yes" if p["test"] else "missing"))

    def show(heading, rows):
        print(heading)
        for r in rows or ["(none)"]:
            print("  " + r)

    show("links to:", ["-> [[%s]] (%s) under \"%s\"" % (b, kind_of(nodes, b), s or "top")
                       for b, s in sorted(links[name].items())])
    show("linked from:", ["<- [[%s]] (%s) under \"%s\"" % (a, kind_of(nodes, a), links[a][name] or "top")
                          for a in sorted(nodes) if name in links[a]])
    show("not linked, but share neighbours:",
         ["[[%s]] via %s" % (b if a == name else a, ", ".join("[[%s]]" % s for s in sh))
          for _, a, b, sh in suggestions(nodes, nb, only=name, min_shared=1)[:10]])
    mentions = unlinked_mentions(nodes, links)
    show("unlinked mentions:",
         ["[[%s]] names it without a link" % s for s, t in mentions if t == name] +
         ["it names [[%s]] without a link" % t for s, t in mentions if s == name])


def main(argv=None):
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(errors="replace")
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = p.add_subparsers(dest="cmd")
    sub.required = True
    s = sub.add_parser("new", help="create a page from a template")
    s.add_argument("type", choices=sorted(TYPES))
    s.add_argument("title")
    s.add_argument("--slug", help="file name without .md (default: from title)")
